"""Parse fetched robots.txt / llms.txt and UA responses. Usage: python3 -I analyze.py <fetch.json> <raw_dir> <out.json>"""
import json, re, sys, collections, os

BOTS = ["GPTBot", "OAI-SearchBot", "ChatGPT-User", "ClaudeBot", "Claude-SearchBot", "Claude-User", "anthropic-ai",
        "PerplexityBot", "Perplexity-User", "Google-Extended", "Applebot-Extended", "CCBot", "Bytespider",
        "meta-externalagent", "Amazonbot", "Googlebot", "Bingbot"]

def is_html(b):
    h = b[:600].lstrip().lower()
    return h.startswith(b"<!doctype") or h.startswith(b"<html") or b"<head" in h or b"<body" in h

def parse_robots(text):
    groups, cur, last_ua = [], None, False
    extras = {"content_signal": [], "sitemap": 0}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if ":" not in line: continue
        k, v = [x.strip() for x in line.split(":", 1)]
        k = k.lower()
        if k == "user-agent":
            if not last_ua: cur = {"agents": [], "rules": []}; groups.append(cur)
            cur["agents"].append(v.lower()); last_ua = True
        elif k in ("allow", "disallow"):
            if cur is not None: cur["rules"].append((k, v))
            last_ua = False
        elif k == "content-signal": extras["content_signal"].append(v)
        elif k == "sitemap": extras["sitemap"] += 1
        # other lines (crawl-delay, host) do not end a group
    return groups, extras

def full_block(rules):
    dis = any(k == "disallow" and v in ("/", "/*") for k, v in rules)
    alw = any(k == "allow" and v in ("/", "/*") for k, v in rules)
    return dis and not alw

def verdict(groups, bot):
    named = [g for g in groups if bot.lower() in g["agents"]]
    if named:
        rules = [r for g in named for r in g["rules"]]
        return "blocked_by_name" if full_block(rules) else "named_not_blocked"
    star = [r for g in groups if "*" in g["agents"] for r in g["rules"]]
    return "blocked_by_wildcard" if full_block(star) else "no_rule"

def main():
    d = json.load(open(sys.argv[1])); raw = sys.argv[2]; out = []
    for s in d["sites"]:
        dom = s["domain"]; r = {"domain": dom, "firm": s["firm"]}
        # robots.txt
        src, body = "", b""
        if s["robots.txt"]["status"] == 200:
            body = open(f"{raw}/{dom}.robots.txt", "rb").read(); src = "live"
        elif s["robots.txt"]["status"] == 404: src = "none_404"
        elif s.get("robots_wayback", {}).get("status") == 200:
            body = open(f"{raw}/{dom}.robots.txt.wayback", "rb").read(); src = "wayback_" + s["robots_wayback"]["capture"][:8]
        else: src = "unreadable"
        if body and is_html(body): src, body = "none_html", b""
        r["robots_source"] = src
        groups, extras = parse_robots(body.decode("utf-8", "replace"))
        r["robots_bytes"] = len(body); r["content_signal"] = " | ".join(extras["content_signal"]); r["sitemap_lines"] = extras["sitemap"]
        r["named_agents"] = sorted({a for g in groups for a in g["agents"] if a != "*"})
        for b in BOTS: r["robots_" + b] = verdict(groups, b) if src != "unreadable" else "unknown"
        # llms.txt
        L = s["llms.txt"]; lb = b""
        p = f"{raw}/{dom}.llms.txt"
        if os.path.exists(p): lb = open(p, "rb").read()
        if L["status"] == 200 and lb.strip() and not is_html(lb) and "html" not in L["ctype"].lower():
            r["llms_txt"] = "yes"; t = lb.decode("utf-8", "replace")
            r["llms_bytes"] = len(lb); r["llms_first_line"] = t.strip().splitlines()[0][:100]
            m = re.search(r"(yoast|rank ?math|aioseo|all in one seo|seopress|generated by[^\n]{0,60}|llms-txt[^\n]{0,40})", t, re.I)
            r["llms_generator_hint"] = m.group(0)[:80] if m else ""
            r["llms_links"] = len(re.findall(r"\]\(https?://", t))
        elif L["status"] in (404, 410): r["llms_txt"] = "no"
        elif L["status"] == 200: r["llms_txt"] = "no_html_page"
        else: r["llms_txt"] = "unknown_" + str(L["status"])
        # UA comparison: same client for all four requests
        h = s["curl"]["home"] if "curl" in s else s["home"]
        r["client"] = "curl" if "curl" in s else "urllib"
        for k in ("browser", "gptbot", "claudebot", "perplexitybot"):
            r["home_" + k] = h[k]["status"]; r["bytes_" + k] = h[k].get("bytes", 0)
        r["server"] = h["browser"].get("server", ""); r["cloudflare"] = bool(h["browser"].get("cf_ray"))
        out.append(r)
    json.dump(out, open(sys.argv[3], "w"), indent=1)
    C = collections.Counter
    print("robots_source", C(re.sub(r"_\d{8}", "", r["robots_source"]) for r in out))
    for b in BOTS: print(f"{b:20}", dict(C(r["robots_" + b] for r in out)))
    print("content_signal", sum(bool(r["content_signal"]) for r in out))
    print("llms", C(r["llms_txt"] for r in out))
    print("named agents:", C(a for r in out for a in r["named_agents"]).most_common(60))
    print("UA patterns (browser,gpt,claude,pplx):", C((r["home_browser"], r["home_gptbot"], r["home_claudebot"], r["home_perplexitybot"]) for r in out).most_common())
main()
